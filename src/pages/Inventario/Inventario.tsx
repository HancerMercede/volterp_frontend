import { useState, useEffect, useCallback, useMemo } from "react";
import { useTranslation } from "react-i18next";
import { useCrudForm, type FormField } from "../../hooks/useCrudForm";
import { useProductoStore } from "../../stores/productoStore";
import { useCategorias } from "../../hooks/useColecciones";
import { useCompanyStore } from "../../stores/companyStore";
import {
  Table,
  Button,
  PageHeader,
  ImageCell,
  ActionButtons,
  Pagination,
  SearchInput,
  Modal,
  ConfirmModal,
  DynamicFormFields,
  VolterpMark,
} from "../../components/UI";
import { usePagination } from "../../hooks/usePagination";
import { ITEMS_PER_PAGE } from "../../config/pagination";
import type { ProductDto } from "../../domain/types";
import styles from "./Inventario.module.css";
import { useFilter } from "../../hooks/useFilter";
import { useDeleteConfirm } from "../../hooks/useDeleteConfirm";
import { money } from "../../utils/currency";

export function Inventario() {
  const { t } = useTranslation();
  const {
    productos,
    error,
    totalCount,
    fetchProductos,
    createProducto,
    updateProducto,
    deleteProducto,
  } = useProductoStore();

  type stockStatus = "all" | "low" | "out";

  // The categories are a lookup: they must not follow the products' page.
  const categories = useCategorias();
  const { currentCompany } = useCompanyStore();
  const [showForm, setShowForm] = useState(false);
  const [searchTerm, setSearchTerm] = useState("");
  const [filterStock, setFilterStock] = useState<stockStatus>("all");
  const { pageNumber, goToPage, getInfo } = usePagination({
    initialPageSize: ITEMS_PER_PAGE,
  });

  useEffect(() => {
    fetchProductos(pageNumber, ITEMS_PER_PAGE);
  }, [pageNumber, fetchProductos]);

  const fields: FormField[] = useMemo(
    () => [
      {
        name: "name",
        label: t("common.name"),
        type: "text",
        required: true,
        section: "formSections.info",
        span: 6,
      },
      {
        name: "categoryId",
        label: t("common.category"),
        type: "select",
        required: true,
        options: categories.map((c) => ({
          value: String(c.id),
          label: c.name,
        })),
        section: "formSections.info",
        span: 4,
      },
      {
        name: "code",
        label: t("common.code"),
        type: "text",
        readonly: true,
        placeholder: t("common.autoGenerated"),
        section: "formSections.info",
        span: 2,
      },
      {
        name: "description",
        label: t("common.description"),
        type: "textarea",
        section: "formSections.info",
        span: 6,
        hint: t("common.showsOnInvoices"),
      },
      {
        name: "price",
        label: t("common.price"),
        type: "number",
        min: 0,
        step: 0.01,
        required: true,
        section: "formSections.pricing",
        span: 2,
      },
      {
        name: "stock",
        label: t("inventario.stock"),
        type: "number",
        min: 0,
        required: true,
        section: "formSections.inventory",
        span: 2,
      },
      {
        name: "imageUrl",
        label: t("common.image"),
        type: "file",
        accept: "image/*",
        sidebar: true,
      },
      {
        name: "isActive",
        label: t("inventario.active"),
        type: "checkbox",
        showOnEdit: true,
        sidebar: true,
        hint: t("common.visibleInSales"),
      },
    ],
    [t, categories],
  );

  const form = useCrudForm({
    fields,
    defaultValues: {
      name: "",
      categoryId: "",
      code: "",
      stock: 0,
      price: 0,
      imageUrl: "",
      description: "",
      isActive: true,
    },
    onCreate: async (data) => {
      const catId = data.categoryId || null;
      const cat = categories.find((c) => c.id === catId);
      await createProducto({
        name: data.name,
        category: cat?.name || "",
        description: data.description || null,
        stock: data.stock,
        price: data.price,
        categoryId: catId,
        companyId: currentCompany?.id,
        imageUrl: data.imageUrl || null,
      });
    },
    onUpdate: async (id, data) => {
      const catId = data.categoryId || null;
      const cat = categories.find((c) => c.id === catId);
      await updateProducto(id, {
        name: data.name,
        category: cat?.name || "",
        description: data.description || null,
        stock: data.stock,
        price: data.price,
        categoryId: catId,
        isActive: data.isActive,
        imageUrl: data.imageUrl || null,
      });
    },
    onSuccess: () => {
      setShowForm(false);
    },
    mapEntityToForm: (entity) => ({
      name: (entity.name as string) ?? "",
      categoryId: (entity.categoryId as string | null) ?? "",
      code: (entity.code as string) ?? "",
      stock: (entity.stock as number) ?? 0,
      price: (entity.price as number) ?? 0,
      imageUrl: (entity.imageUrl as string) ?? "",
      description: (entity.description as string) ?? "",
      isActive: (entity.isActive as boolean) ?? true,
    }),
  });

  // Intercept category select to also update the category name string
  const handleFieldChange = useCallback(
    (name: string, value: unknown) => {
      if (name === "categoryId") {
        const catId = value ? (value as string) : null;
        const cat = categories.find((c) => c.id === catId);
        form.setFieldValue("categoryId", value);
        form.setFieldValue("category", cat?.name ?? "");
      } else {
        form.setFieldValue(name, value);
      }
    },
    [categories, form],
  );

  const filteredProductos = useFilter({
    data: productos,
    searchTerm,
    searchFields: (p) => [p.name, p.category, p.code],
    filter: (p) => {
      if (filterStock === "low") return p.stock > 0 && p.stock < 10;
      if (filterStock === "out") return p.stock === 0;
      return true;
    },
  });

  const paginationInfo = getInfo(totalCount);

  const handleEdit = (producto: ProductDto) => {
    form.handleEdit(producto, producto.id);
    setShowForm(true);
  };

  const {
    showDeleteConfirm,
    deleteId,
    handleDelete,
    confirmDelete,
    cancelDelete,
  } = useDeleteConfirm({
    onDelete: deleteProducto,
    successMessage: t("inventario.productDeleted"),
  });

  const pendingProduct = productos.find((p) => p.id === deleteId) ?? null;

  const columns = [
    { key: "code", header: t("common.code") },
    {
      key: "name",
      header: t("common.product"),
      render: (p: ProductDto) => (
        <ImageCell
          src={p.imageUrl || `https://i.pravatar.cc/150?img=${p.id}`}
          name={p.name}
          subtext={p.category}
          type="product"
        />
      ),
    },
    { key: "category", header: t("common.category") },
    { key: "description", header: t("common.description") },
    {
      key: "stock",
      header: t("inventario.stock"),
      render: (p: ProductDto) => (
        <span
          className={
            p.stock === 0
              ? styles.outOfStock
              : p.stock < 10
                ? styles.lowStock
                : ""
          }
        >
          {p.stock}
        </span>
      ),
    },
    {
      key: "price",
      header: t("common.price"),
      render: (p: ProductDto) => `$${p.price.toLocaleString()}`,
    },
    {
      key: "actions",
      header: t("common.actions"),
      render: (p: ProductDto) => (
        <ActionButtons
          onEdit={() => handleEdit(p)}
          onDelete={() => handleDelete(p.id)}
        />
      ),
    },
  ];

  return (
    <div>
      <PageHeader
        title={t("inventario.title")}
        subtitle={t("inventario.subtitle")}
      >
        <Button
          onClick={() => {
            form.reset();
            setShowForm(true);
          }}
        >
          + {t("inventario.newProduct")}
        </Button>
      </PageHeader>

      <div className={styles.filters}>
        <SearchInput
          value={searchTerm}
          onChange={(value) => {
            setSearchTerm(value);
            goToPage(1);
          }}
          placeholder={t("inventario.searchPlaceholder")}
          width="240px"
        />
        <select
          className={styles.filter}
          value={filterStock}
          onChange={(e) => {
            setFilterStock(e.target.value as stockStatus);
            goToPage(1);
          }}
        >
          <option value="all">{t("inventario.all")}</option>
          <option value="low">{t("inventario.lowStock")}</option>
          <option value="out">{t("inventario.outOfStock")}</option>
        </select>
      </div>

      {error && <p style={{ color: "red" }}>{error}</p>}

      <Modal
        isOpen={showForm}
        onClose={() => {
          setShowForm(false);
          form.reset();
        }}
        size="lg"
        icon={<VolterpMark size={40} />}
        title={
          form.editingId
            ? t("inventario.editProduct")
            : t("inventario.newProduct")
        }
        subtitle={
          form.editingId
            ? form.values.name || t("common.newRecordSubtitle")
            : t("common.newRecordSubtitle")
        }
        footerStatus={
          form.isDirty
            ? t("common.unsavedChanges")
            : t("common.noPendingChanges")
        }
        dirty={form.isDirty}
        error={form.submitError}
        noValidate
        onSubmit={form.handleSubmit}
        submitLabel={
          form.editingId ? t("common.saveChanges") : t("common.create")
        }
        submitVariant="dark"
        cancelLabel={t("common.cancel")}
        closeLabel={t("common.close")}
      >
        <DynamicFormFields
          fields={fields}
          values={form.values}
          errors={form.errors}
          editingId={form.editingId}
          onChange={handleFieldChange}
        />
      </Modal>

      <Table data={filteredProductos} columns={columns} />

      <Pagination pagination={paginationInfo} onPageChange={goToPage} />

      <ConfirmModal
        isOpen={showDeleteConfirm}
        onConfirm={confirmDelete}
        onCancel={cancelDelete}
        title={`${t("common.delete")} ${t("common.product")}`}
        message={t("inventario.deleteConfirm")}
        confirmLabel={t("common.confirmDeleteAction")}
        cancelLabel={t("common.cancel")}
        context={
          pendingProduct
            ? {
                title: `${t("common.product")} #${pendingProduct.code}`,
                subtitle: [pendingProduct.name, pendingProduct.categoryName]
                  .filter(Boolean)
                  .join(" · "),
                amount: money(pendingProduct.price),
              }
            : undefined
        }
      />
    </div>
  );
}
